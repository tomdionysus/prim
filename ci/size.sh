#!/usr/bin/env bash
#
# Code size of each part of the library, by target, into docs/sizes.md: the
# functions that do not depend on an element type, summed by symbol from
# images that use every primitive, at -Os: the suite for each Cortex-M core
# (ci/arm.sh builds them) and the ESP32-S3 test app, built here at -Os. Code
# inlined into a caller counts to the caller, as it does in a program.
# Template code, which each element type adds, is not counted.
#
#   ci/size.sh
#
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd -P)
s3b=$here/build/size-s3
s3=$s3b/prim_target.elf
s3nm=$(ls "${IDF_TOOLS_PATH:-$HOME/.espressif}"/tools/xtensa-esp-elf/*/xtensa-esp-elf/bin/xtensa-esp32s3-elf-nm 2>/dev/null | head -1)
[[ -n $s3nm ]] || { echo "no xtensa-esp32s3-elf-nm: install ESP-IDF" >&2; exit 1; }

for core in m0 m3 m7 m33; do
  [[ -f $here/build/arm-$core/prim_tests.elf ]] || "$here/ci/arm.sh" "$core" >/dev/null
done

# The S3 test app as target/ builds it, but at -Os, as a release would be.
mkdir -p "$s3b"
echo CONFIG_COMPILER_OPTIMIZATION_SIZE=y >"$s3b/sdkconfig.size"
(
  . "${IDF_PATH:-$HOME/esp/esp-idf}/export.sh" >/dev/null 2>&1
  idf.py -C "$here/target" -B "$s3b" -DSDKCONFIG="$s3b/sdkconfig" \
    -DSDKCONFIG_DEFAULTS="$here/target/sdkconfig.defaults;$here/target/sdkconfig.heltec_v3;$s3b/sdkconfig.size" \
    build >"$s3b/build.log" 2>&1
) || { echo "S3 build failed: see $s3b/build.log" >&2; exit 1; }
grep -q '^CONFIG_COMPILER_OPTIMIZATION_SIZE=y' "$s3b/sdkconfig" || { echo "S3 build is not at -Os" >&2; exit 1; }

# Octets by part, from the demangled names of the code symbols. A library
# symbol no part claims is reported, so a new part cannot be missed.
sizes() {  # nm elf
  "$1" -S -C -t d "$2" | awk '
    $3 ~ /^[tTwW]$/ {
      name = $0; sub(/^[^ ]+ [^ ]+ [^ ]+ /, "", name)
      if (name !~ /^prim::/ || name ~ /</) next
      if (name ~ /^prim::Arena::/) part = "Arena"
      else if (name ~ /^prim::TrieCore::/) part = "Trie"
      else if (name ~ /^prim::Pool::/) part = "Pool"
      else if (name ~ /^prim::(rb_|detail::(red|replace|rotate)\()/) part = "Tree"
      else if (name ~ /^prim::(TimerQueue|Timer)::/) part = "TimerQueue"
      else if (name ~ /^prim::(halfsiphash|hash32|hash_seed)\(|^prim::detail::(le32|rounds|hash_end)\(/) part = "HalfSipHash"
      else if (name ~ /^prim::HashCore::/) part = "Hash"
      else if (name ~ /^prim::Account::/) part = "Account"
      else if (name ~ /^prim::RingCore::/) part = "Ring"
      else if (name ~ /^prim::VecCore::/) part = "Vec"
      else if (name ~ /^prim::clz(32|64)_portable\(/) next  # called only by its test under GCC
      else { print "unattributed: " name > "/dev/stderr"; next }
      sum[part] += $2 + 0
    }
    END { for (p in sum) print p "\t" sum[p] }'
}

declare -A size total
cols=(s3 m0 m3 m7 m33)
for c in "${cols[@]}"; do
  if [[ $c == s3 ]]; then out=$(sizes "$s3nm" "$s3"); else out=$(sizes arm-none-eabi-nm "$here/build/arm-$c/prim_tests.elf"); fi
  while IFS=$'\t' read -r part n; do [[ -n $part ]] && size[$part,$c]=$n; done <<<"$out"
done

commas() { printf "%'d" "$1"; }
idf=$("${s3nm%nm}gcc" -dumpversion)
arm=$(arm-none-eabi-gcc -dumpversion)
parts=(Arena Trie Pool Tree TimerQueue HalfSipHash Hash Account Ring Vec)
{
  echo "# prim: code size by target"
  echo
  echo "Generated by \`ci/size.sh\` on $(date -I) at \`$(git -C "$here" rev-parse --short HEAD)\`."
  echo "Do not edit by hand."
  echo
  echo "Octets of code for each part's functions that do not depend on an"
  echo "element type, read by symbol from images that use every primitive, at"
  echo "\`-Os\`: the test app for the ESP32-S3, with ESP-IDF's GCC $idf, and the"
  echo "suite for each Cortex-M core, with the Arm GNU toolchain's GCC $arm. Code"
  echo "inlined into a caller counts to the caller, as in a program; each element"
  echo "type a template is used with adds a few dozen octets more."
  echo
  echo "| Part | ESP32-S3 | Cortex-M0 | Cortex-M3 | Cortex-M7 | Cortex-M33 |"
  echo "| --- | --- | --- | --- | --- | --- |"
  for p in "${parts[@]}"; do
    label="\`$p\`"; [[ $p == Tree ]] && label="\`Tree\` and the node functions"
    row="| $label"
    for c in "${cols[@]}"; do
      n=${size[$p,$c]:-0}; total[$c]=$(( ${total[$c]:-0} + n )); row+=" | $(commas "$n")"
    done
    echo "$row |"
  done
  row="| All"; for c in "${cols[@]}"; do row+=" | $(commas "${total[$c]}")"; done; echo "$row |"
} >"$here/docs/sizes.md"
cat "$here/docs/sizes.md"
